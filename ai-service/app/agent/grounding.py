"""
Grounding Verification Module for AI Agent Citations.

Enforces strict verification of model-cited ticket IDs and KB article IDs
against evidence actually retrieved by tool calls during the specific agent execution.
"""

import logging
from typing import Any, Dict, List, Set, Tuple

from app.agent.schemas import Analysis, GroundingResult, ToolCallRecord

logger = logging.getLogger(__name__)


def extract_tool_grounded_ids(tool_calls: List[ToolCallRecord]) -> Tuple[Set[int], Set[int]]:
    """
    Collects all ticket IDs and KB article/chunk IDs returned by tools during this specific execution run.

    Returns:
        Tuple of (grounded_ticket_ids, grounded_kb_ids).
    """
    grounded_ticket_ids: Set[int] = set()
    grounded_kb_ids: Set[int] = set()

    for call in tool_calls:
        if call.error or call.result is None:
            continue

        result = call.result

        # 1. search_similar_tickets returns list of ticket records
        if call.tool_name == "search_similar_tickets" and isinstance(result, list):
            for item in result:
                if isinstance(item, dict) and "ticket_id" in item:
                    try:
                        grounded_ticket_ids.add(int(item["ticket_id"]))
                    except (ValueError, TypeError):
                        pass

        # 2. get_ticket_history returns ticket record
        elif call.tool_name == "get_ticket_history" and isinstance(result, dict):
            if "ticket_id" in result:
                try:
                    grounded_ticket_ids.add(int(result["ticket_id"]))
                except (ValueError, TypeError):
                    pass

        # 3. search_kb returns list of KB chunk records with article_id and chunk_id
        elif call.tool_name == "search_kb" and isinstance(result, list):
            for item in result:
                if isinstance(item, dict):
                    if "article_id" in item:
                        try:
                            grounded_kb_ids.add(int(item["article_id"]))
                        except (ValueError, TypeError):
                            pass
                    if "chunk_id" in item:
                        try:
                            grounded_kb_ids.add(int(item["chunk_id"]))
                        except (ValueError, TypeError):
                            pass

    return grounded_ticket_ids, grounded_kb_ids


def verify_grounding(
    analysis: Analysis,
    grounded_ticket_ids: Set[int],
    grounded_kb_ids: Set[int],
) -> GroundingResult:
    """
    Validates model-cited IDs against tool-collected grounded IDs.

    Args:
        analysis: Final Analysis output generated by the agent.
        grounded_ticket_ids: Set of ticket IDs returned by tools.
        grounded_kb_ids: Set of KB IDs returned by tools.

    Returns:
        GroundingResult with valid and unsupported references.
    """
    valid_tickets: List[int] = []
    unsupported_tickets: List[int] = []

    for tid in analysis.related_ticket_ids:
        if tid in grounded_ticket_ids:
            valid_tickets.append(tid)
        else:
            unsupported_tickets.append(tid)

    valid_kb: List[int] = []
    unsupported_kb: List[int] = []

    for kbid in analysis.kb_sources:
        if kbid in grounded_kb_ids:
            valid_kb.append(kbid)
        else:
            unsupported_kb.append(kbid)

    is_valid = len(unsupported_tickets) == 0 and len(unsupported_kb) == 0

    if not is_valid:
        logger.warning(
            "Grounding check failed: unsupported tickets=%s, unsupported kb=%s",
            unsupported_tickets,
            unsupported_kb,
        )

    return GroundingResult(
        is_valid=is_valid,
        grounded_ticket_ids=valid_tickets,
        unsupported_ticket_ids=unsupported_tickets,
        grounded_kb_ids=valid_kb,
        unsupported_kb_ids=unsupported_kb,
    )


def sanitize_grounded_analysis(analysis: Analysis, grounding: GroundingResult) -> Analysis:
    """
    Returns an Analysis instance sanitized so that only verified, grounded IDs remain.
    """
    return Analysis(
        root_cause=analysis.root_cause,
        confidence=analysis.confidence,
        suggested_steps=analysis.suggested_steps,
        related_ticket_ids=grounding.grounded_ticket_ids,
        kb_sources=grounding.grounded_kb_ids,
    )
